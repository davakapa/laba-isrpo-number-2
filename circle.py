import math


def area(r):
#функция получает на вход число , возвращает произведение квадрата числа и числа пи    
	return math.pi * r * r

def perimeter(r):
#возвращает удвоенное произведение пи и десятичного числа
#параметры: r (int) - десятичное число
#возвращаемое значение perimeter (int) число равное удвоенному произведению пи и десятичного числа r
	return 2 * math.pi * r
